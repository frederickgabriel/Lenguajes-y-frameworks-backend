function suma(a, b) {
    return a + b;
}

function resta(a, b) {
    return a - b;
}

function multiplicacion(a, b) {
    return a * b;
}

function division(a, b) {
    return a / b;
}

// Exportar las funciones
module.exports = {
    suma,
    resta,
    multiplicacion,
    division
};

